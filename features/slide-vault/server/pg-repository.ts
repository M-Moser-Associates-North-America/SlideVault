/** Every ready uploaded deck's slides in slide order, for deck sections and named words (FD-57, FD-56). */
export async function listDeckSlidesPg(): Promise<DeckSlidesPg[]> {
  const rows = await sql<{ id: string; deck_id: string; client: string; project_location: string | null; source_filename: string | null; title: string | null; text: string | null; slide_type: string | null }>(
    `select s.id, s.deck_id, d.client, d.project_location, d.source_filename, s.title, s.text, s.slide_type from slides s join decks d on d.id = s.deck_id where d.status = 'ready' and d.archived_at is null order by s.deck_id, s.slide_number`,
  );
  const decks = new Map<string, DeckSlidesPg>();
  for (const r of rows) {
    let deck = decks.get(r.deck_id);
    if (!deck) decks.set(r.deck_id, (deck = { id: r.deck_id, client: r.client, location: r.project_location ?? folderInfo(r.source_filename ?? '').location, slides: [] }));
    deck.slides.push({ id: r.id, title: r.title ?? '', text: r.text ?? '', type: r.slide_type });
  }
  return [...decks.values()];
}

/** Every ready uploaded deck and its slides (GET /library). */
export async function listLibraryPg(): Promise<{ decks: LibraryDeck[]; slides: Omit<LibrarySlide, 'duplicateGroupId'>[] }> {
  const deckRows = await sql<DeckRow & { uploaded_at: Date | string | null }>(`select * from decks where status = 'ready' and archived_at is null order by uploaded_at desc`);
  const decks: LibraryDeck[] = deckRows.map((d) => ({
    id: d.id,
    title: d.title,
    client: d.client && d.client !== 'Unknown client' ? d.client : null,
    year: d.year,
    category: d.category,
    bestOfTheBest: d.best_of_the_best,
    slideSize: d.slide_size,
    versionId: d.file_hash,
    uploadedAt: d.uploaded_at instanceof Date ? d.uploaded_at.toISOString() : d.uploaded_at,
    source: 'upload',
  }));
  const rows = await sql<{ id: string; deck_id: string; slide_number: number; title: string | null; text: string | null; is_hidden_in_source: boolean }>(
    `select s.id, s.deck_id, s.slide_number, s.title, s.text, s.is_hidden_in_source
     from slides s join decks d on d.id = s.deck_id where d.status = 'ready' and d.archived_at is null order by s.deck_id, s.slide_number`,
  );
  const slides = rows.map((r) => ({
    id: r.id,
    deckId: r.deck_id,
    slideNumber: r.slide_number,
    title: r.title || `Slide ${r.slide_number}`,
    text: r.text ?? '',
    hiddenInSource: r.is_hidden_in_source,
    previewPath: `/slides/${r.id}/preview`,
  }));
  return { decks, slides };
}
